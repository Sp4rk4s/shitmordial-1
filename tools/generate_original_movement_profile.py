"""Generate guarded original-code capsule metadata from the exact supplied dump.

Capstone is needed only for this offline generator, never in the game DLL.
"""
import hashlib
from pathlib import Path
import struct
import sys

ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT/'build/analysis-python'))
from capstone import Cs,CS_ARCH_X86,CS_MODE_32


def main():
    raw=(ROOT/'primordial.bin').read_bytes()
    assert hashlib.sha256(raw).hexdigest()=='e16dd0ecf4f763be49139d5edff21f2e6106cff1040e2f6a684fabcb7eeb9768'
    md=Cs(CS_ARCH_X86,CS_MODE_32)
    profiles=[('bhop',0xF8674,0xF870E),('duck',0xF85F3,0xF8623),
              ('strafe',0xF92D0,0xF976D),('stop',0xF8713,0xF888E),
              ('ground',0x369540,0x369561)]
    fields={0x2D9CB32C:'water',0x2D8F778B:'flags',0x2D8F1D4F:'velocity',0x2D8F003C:'ground'}
    lines=['// Generated by tools/generate_original_movement_profile.py from exact SHA256-verified dump.']
    def profile(start,end):
        digest=','.join(f'0x{x:02X}' for x in hashlib.sha256(raw[start:end]).digest())
        return f'{{0x{start:X},0x{end-start:X},{{{digest}}}}}'
    for name,start,end in profiles:
        calls=[];operands=[];covered=start
        instructions={i.address:i for i in md.disasm(raw[start:end],start)}
        reachable=set();pending=[start]
        while pending:
            address=pending.pop()
            if address==end or address in reachable:continue
            ins=instructions[address];reachable.add(address)
            if ins.mnemonic.startswith('ret'):continue
            if ins.mnemonic.startswith('j') and ins.op_str.startswith('0x'):
                destination=int(ins.op_str,16)
                assert start<=destination<=end,'reachable outgoing branch'
                pending.append(destination)
                if ins.mnemonic=='jmp':continue
            pending.append(address+ins.size)
        # F86D1..F86EE belongs to an unrelated weapon block with no incoming
        # edge from the bunnyhop entry. Preserve its bytes, never its behavior.
        if name=='bhop':assert not any(0xF86D1<=r<0xF86EF for r in reachable)
        for ins in instructions.values():
            assert ins.address==covered;covered+=ins.size
            data=ins.bytes
            if data[0] in (0xE8,0xE9) and ins.size==5:
                target=ins.address+5+struct.unpack_from('<i',data,1)[0]
                if not start<=target<=end:
                    assert data[0]==0xE8 or ins.address not in reachable,'outgoing jump needs explicit continuation proof'
                    if data[0]==0xE8:calls.append((ins.address-start+1,target))
            elif ins.mnemonic.startswith('j') and ins.op_str.startswith('0x'):
                assert start<=int(ins.op_str,16)<=end or ins.address not in reachable,'outgoing conditional branch'
            for address,field in fields.items():
                offset=data.find(struct.pack('<I',address))
                if offset>=0:operands.append((ins.address-start+offset,address,field))
        assert covered==end
        lines.append(f'constexpr Profile {name}_profile={profile(start,end)};')
        calls_text=','.join(f'{{0x{o:X},0x{t:X}}}' for o,t in calls) or '{~0u,0}'
        operands_text=','.join(f'{{0x{o:X},0x{a:X},&Fields::{f}}}' for o,a,f in operands) or '{~0u,0,nullptr}'
        lines.extend([f'constexpr Relocation {name}_calls[]={{{calls_text}}};',f'constexpr Operand {name}_operands[]={{{operands_text}}};'])
    helpers=[(0xA06C0,0x37),(0xF7A50,0x6D3),(0x3748D0,0x29),(0xD3C70,0x107),
             (0xB2AD0,0x18F),(0xAEB40,0xA3),(0x33AE00,0xE4),(0x32C360,6)]
    lines.append('constexpr Profile guards[]={'+','.join(profile(s,e) for _,s,e in profiles)+','+
                 ','.join(profile(s,s+n) for s,n in helpers)+'};')
    (ROOT/'primordial_loader/src/original_movement_profile.inc').write_text('\n'.join(lines)+'\n')
    print('Generated five original-code profiles with guarded operands and verified rel32 destinations.')


if __name__=='__main__':main()
