"""Generate stable menu guards from exact on-disk binaries, without a game process."""
import hashlib
import json
from pathlib import Path
import struct

ROOT=Path(__file__).resolve().parents[1]
BASELINE='e16dd0ecf4f763be49139d5edff21f2e6106cff1040e2f6a684fabcb7eeb9768'
METHODS=[('vgui2.dll','VGUI_Panel009',36,0x19400),('vgui2.dll','VGUI_Panel009',41,0x19520),
    ('vguimatsurface.dll','VGUI_Surface031',12,0xD670),('vguimatsurface.dll','VGUI_Surface031',13,0xD7C0),
    ('vguimatsurface.dll','VGUI_Surface031',71,0x10F80),('vguimatsurface.dll','VGUI_Surface031',72,0x10FA0),
    ('vguimatsurface.dll','VGUI_Surface031',79,0x11180),('vguimatsurface.dll','VGUI_Surface031',147,0x148A0),
    ('engine.dll','VEngineClient014',5,0xB63E0),('engine.dll','VEngineClient014',26,0xB6D40),
    ('client.dll','VClient018',0,0x25FC10),('inputsystem.dll','InputSystemVersion001',40,0x2B20),
    ('inputsystem.dll','InputSystemVersion001',46,0x2C00),
    ('materialsystem.dll','VMaterialSystem080',84,0x1AF30)]
PAYLOAD=[0x2E04D0,0x3504B0,0x351AB0,0x3609A0,0x3609E0,0x360CE0,0x34A4B0,0x34B860,0x34DB30,0x32EF80,0x343ED0,0x32E410,0x336EA0,0x2CAB40,0x32BA40,0x162FA0]

class PE:
    def __init__(self,data):
        self.data=data
        nt=struct.unpack_from('<I',data,60)[0]
        assert data[:2]==b'MZ' and data[nt:nt+4]==b'PE\0\0'
        machine,count,self.timestamp=struct.unpack_from('<HHI',data,nt+4)
        assert machine==0x14C
        opt=nt+24
        assert struct.unpack_from('<H',data,opt)[0]==0x10B
        self.preferred_base=struct.unpack_from('<I',data,opt+28)[0]
        self.image_size=struct.unpack_from('<I',data,opt+56)[0]
        table=opt+struct.unpack_from('<H',data,nt+20)[0]
        self.sections=[struct.unpack_from('<4I',data,table+40*i+8) for i in range(count)]
        rva,length=struct.unpack_from('<II',data,opt+96+5*8)
        self.relocations=[]
        offset=self.offset(rva)
        cursor=0
        while cursor<length:
            page,size=struct.unpack_from('<II',data,offset+cursor)
            assert size>=8 and size%2==0 and cursor+size<=length
            for entry, in struct.iter_unpack('<H',data[offset+cursor+8:offset+cursor+size]):
                kind=entry>>12
                assert kind in (0,3),('Unsupported x86 relocation',kind)
                if kind==3:self.relocations.append(page+(entry&0xFFF))
            cursor+=size
    def offset(self,rva):
        for virtual_size,virtual,raw_size,raw in self.sections:
            if virtual<=rva<virtual+min(virtual_size,raw_size):return raw+rva-virtual
        raise ValueError(('RVA outside stored sections',hex(rva)))
    def read(self,rva,length):
        offset=self.offset(rva)
        return self.data[offset:offset+length]

def values(data):return ','.join('0x%02X'%b for b in data)

def main():
    raw=(ROOT/'primordial.bin').read_bytes()
    assert hashlib.sha256(raw).hexdigest()==BASELINE
    facts=json.loads((ROOT/'analysis/menu/source-interface-state-10836.json').read_text())['factories']
    # New native-frame dependency independently captured from the public
    # factory and current vtable; the module lives beside vguimatsurface.dll.
    facts['materialsystem.dll']={
        'path':str(Path(facts['vguimatsurface.dll']['path']).with_name('materialsystem.dll')),
        'disk_sha256':'011e6fb57fa1856ae946a442a2aa2c930d5b15447b03c7e67a64337571f92cce'}
    lines=['// Exact installed-build identity and relocation-aware guards. No runtime capture needed.',
        '// Generated by tools/generate_menu_profile.py; source identity recorded in analysis/menu/menu-integration-profile.json.',
        '#pragma once','#include <cstdint>','namespace menu_profile {',
        'struct Bytes { unsigned rva,size; unsigned char bytes[32]; };','inline constexpr Bytes payload[] = {']
    for rva in PAYLOAD:lines.append('{0x%X,24,{%s}},'%(rva,values(raw[rva:rva+24])))
    lines+=['};','struct Module { const char *name; unsigned preferred_base,timestamp,image_size; unsigned char sha256[32]; };',
            'inline constexpr Module modules[] = {']
    parsed={};module_indices={};evidence=dict(raw_sha256=BASELINE,source='Installed on-disk PE files; no process access or target calls',modules=[],methods=[])
    for name in dict.fromkeys(m[0] for m in METHODS):
        info=facts[name];data=Path(info['path']).read_bytes();digest=hashlib.sha256(data).hexdigest()
        assert digest==info['disk_sha256'],('Installed game build changed',name)
        pe=PE(data);parsed[name]=pe;module_indices[name]=len(module_indices)
        lines.append('{"%s",0x%X,0x%X,0x%X,{%s}},'%(name,pe.preferred_base,pe.timestamp,pe.image_size,values(bytes.fromhex(digest))))
        evidence['modules'].append(dict(name=name,path=info['path'],sha256=digest,preferred_base=hex(pe.preferred_base),timestamp=hex(pe.timestamp),image_size=hex(pe.image_size)))
    lines+=['};','struct SourceGuard { unsigned module_index; const char *version; unsigned slot,rva,size,relocations; unsigned char bytes[32]; };',
            'inline constexpr SourceGuard source[] = {']
    for name,version,slot,rva in METHODS:
        pe=parsed[name];relocs=[address-rva for address in pe.relocations if rva<=address<rva+24]
        assert all(i+4<=32 for i in relocs)
        mask=sum(1<<i for i in relocs)
        lines.append('{%u,"%s",%u,0x%X,24,0x%X,{%s}},'%(module_indices[name],version,slot,rva,mask,values(pe.read(rva,28))))
        evidence['methods'].append(dict(module=name,version=version,slot=slot,rva=hex(rva),relocation_offsets=relocs,disk_bytes=pe.read(rva,28).hex()))
    lines+=['};','inline constexpr unsigned timing_slot_rva=0xDAF8E0;',
        'inline constexpr unsigned long long raw_checksum=0xA5946EB23B96DEE7ULL;',
        'struct Font { unsigned rva; const char *face; int tall,weight,flags,lo,hi; };','inline constexpr Font fonts[] = {']
    for record in json.loads((ROOT/'analysis/menu/all-default-font-record-associations.json').read_text())['records']:
        assert len(record['exact_record_candidates'])==1
        f=record['settings'];rva=int(record['exact_record_candidates'][0]['rva'],16)
        lines.append('{0x%X,"%s",%u,%u,%u,%u,%u},'%(rva,f['face'],f['tall'],f['weight'],f['flags'],f['range_min'],f['range_max']))
    lines+=['};','}']
    (ROOT/'primordial_loader/src/menu_profile_data.h').write_text('\n'.join(lines)+'\n')
    (ROOT/'analysis/menu/menu-integration-profile.json').write_text(json.dumps(evidence,indent=2)+'\n')
    print(f'Generated stable guards for{len(parsed)} exact Source DLLs and{len(METHODS)} methods from disk.')

if __name__=='__main__':main()
