"""Guard/relocate original FOV code without translating feature behavior."""
import hashlib
from pathlib import Path
import struct
import sys
ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT/'build/analysis-python'))
from capstone import Cs,CS_ARCH_X86,CS_MODE_32


def main():
    raw=(ROOT/'primordial.bin').read_bytes()
    assert hashlib.sha256(raw).hexdigest()=='e16dd0ecf4f763be49139d5edff21f2e6106cff1040e2f6a684fabcb7eeb9768'
    functions=[(0x14FE90,0x92),(0xA1CD0,0x98),(0x36ABF0,0x66),(0x369370,0x21),(0x1500BD,0x1E)]
    mapping={0x2DBDB5D3:'scoped',0x2DA842AE:'item',0x2DA91016:'weapon',0x2D8F9170:'life',0x2DA9DC0C:'observer_mode',0x2DAF0360:'observer_target',0x2D9B7EE7:'resource_alive'}
    profiles=[];calls=[];operands=[];md=Cs(CS_ARCH_X86,CS_MODE_32)
    for start,size in functions:
        digest=','.join(f'0x{x:02X}' for x in hashlib.sha256(raw[start:start+size]).digest())
        profiles.append(f'{{0x{start:X},0x{size:X},{{{digest}}}}}')
        refs=[];fields=[];covered=0
        for ins in md.disasm(raw[start:start+size],start):
            covered+=ins.size
            if ins.mnemonic.startswith('j'):
                assert start<=int(ins.op_str,16)<start+size
            if ins.bytes[0]==0xE8:
                target=ins.address+5+struct.unpack_from('<i',ins.bytes,1)[0]
                assert target in [r for r,n in functions],hex(target)
                refs.append(f'{{0x{ins.address-start+1:X},0x{target:X}}}')
            for address,name in mapping.items():
                offset=ins.bytes.find(struct.pack('<I',address))
                if offset>=0:fields.append(f'{{0x{ins.address-start+offset:X},0x{address:X},&Fields::{name}}}')
        assert covered==size
        if len(calls)<4:
            calls.append('{'+','.join(refs+['{~0u,0}'])+'}')
            operands.append('{'+','.join(fields+['{~0u,0,nullptr}'])+'}')
    text='// Exact original dump; generated by tools/generate_original_fov_profile.py.\n'
    text+='constexpr Profile profiles[]={'+','.join(profiles)+'};\n'
    text+='constexpr Relocation relocations[4][4]={'+','.join(calls)+'};\n'
    text+='constexpr Operand operands[4][4]={'+','.join(operands)+'};\n'
    (ROOT/'primordial_loader/src/original_fov_profile.inc').write_text(text)
    print('Generated original FOV callback, three native helpers and native render-add leaf profiles.')


if __name__=='__main__':main()
